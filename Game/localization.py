def translate(text: str, language: str) -> str:
    if language != "en":
        return text
    translated = ENGLISH.get(text)
    if translated is not None:
        return translated
    piece_count = re.fullmatch(r"(Pesec|Kun|Strelec|Vez|Dama|Kral): (\d+)/(\d+)", text)
    if piece_count:
        return (
            f"{ENGLISH[piece_count.group(1)]}: "
            f"{piece_count.group(2)}/{piece_count.group(3)}"
        )
    for pattern, replacement in _DYNAMIC:
        if pattern.fullmatch(text):
            return pattern.sub(replacement, text)
    return text
